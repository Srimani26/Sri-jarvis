  /**
   * Serve a built static file for preview
   */
  public getBuildFile(projectSlug: string, fileName = 'index.html', workspaceRoot = process.cwd()): { content: Buffer; contentType: string } | null {
    const safeSlug = projectSlug.replace(/[^a-z0-9_-]/g, '_')
    const safeFile = (fileName || 'index.html').replace(/[^a-zA-Z0-9._-]/g, '_')
    const filePath = join(workspaceRoot, 'artifacts', 'builds', safeSlug, safeFile)

    if (!existsSync(filePath)) {
      return null
    }

    const content = readFileSync(filePath)
    let contentType = 'text/plain'
    if (safeFile.endsWith('.html')) contentType = 'text/html; charset=UTF-8'
    else if (safeFile.endsWith('.css')) contentType = 'text/css; charset=UTF-8'
    else if (safeFile.endsWith('.js')) contentType = 'application/javascript; charset=UTF-8'
    else if (safeFile.endsWith('.json')) contentType = 'application/json'

    return { content, contentType }
  }
