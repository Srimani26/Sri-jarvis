import { existsSync, mkdirSync, writeFileSync, readFileSync } from 'node:fs'
import { join } from 'node:path'

export type ProjectScope = 'SCOPE_SPA' | 'SCOPE_FULLSTACK'

export function classifyProjectScope(directive: string): ProjectScope {
  const lower = directive.toLowerCase()
  if (
    lower.includes('fullstack') ||
    lower.includes('full-stack') ||
    lower.includes('saas') ||
    lower.includes('backend') ||
    lower.includes('prisma') ||
    lower.includes('database') ||
    lower.includes('express') ||
    lower.includes('api route') ||
    lower.includes('multi-file') ||
    lower.includes('react')
  ) {
    return 'SCOPE_FULLSTACK'
  }
  return 'SCOPE_SPA'
}

export interface AppBuilderParams {
  projectSlug: string
  appType?: 'react_spa' | 'landing_page' | 'fullstack'
  specification: {
    title?: string
    description?: string
    theme?: string
    features?: string[]
    htmlContent?: string
    jsContent?: string
    cssContent?: string
    components?: Array<{ name: string; type: string; props?: Record<string, any> }>
  }
}

