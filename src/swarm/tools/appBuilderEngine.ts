  document.getElementById('battery-kwh-val').textContent = batteryKwh + ' kWh';
  document.getElementById('energy-rate-val').textContent = '$' + energyRate.toFixed(2) + ' / kWh';

  // Cost Equations
  const roofingCost = roofSqft * roofRate;
