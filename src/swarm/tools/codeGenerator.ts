import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { resolve, relative, isAbsolute } from 'node:path'
import { executeGithubManageFile } from './toolRegistry'

export interface CodeEngineerParams {
  targetFilePath: string
  action: 'CREATE' | 'REFACTOR' | 'INSPECT'
  instructions: string
  codeSnippet?: string
}

export interface CodeEngineerResult {
  status: 'SUCCESS' | 'ERROR'
  action: 'CREATE' | 'REFACTOR' | 'INSPECT'
  path: string
  lines?: number
  contentPreview?: string
  diffSummary?: string
  message: string
}

/**
 * Validate that target file is strictly inside project root sandbox
 */
function resolveSafePath(filePath: string): string {
  const root = process.cwd()
  const resolved = resolve(root, filePath)
  const rel = relative(root, resolved)

  if (rel.startsWith('..') || isAbsolute(rel)) {
    throw new Error(`Security Violation: Target path "${filePath}" attempts to traverse outside project root.`)
  }

  return resolved
}

/**
 * Syntax and structural sanity check for code snippets
 */
function validateCodeSyntax(code: string, extension: string): { valid: boolean; error?: string } {
  if (!code || code.trim().length === 0) {
    return { valid: false, error: 'Code content cannot be empty' }
  }

  // Check balanced parentheses, brackets, and braces
  const stack: string[] = []
  const pairs: Record<string, string> = { ')': '(', ']': '[', '}': '{' }

  for (let i = 0; i < code.length; i++) {
    const char = code[i]
    if (char === '(' || char === '[' || char === '{') {
      stack.push(char)
    } else if (char === ')' || char === ']' || char === '}') {
      const top = stack.pop()
      if (top !== pairs[char]) {
        return {
          valid: false,
          error: `Syntax Warning: Mismatched closing token "${char}" at index ${i}`
        }
      }
    }
  }

  if (stack.length > 0) {
    return {
      valid: false,
      error: `Syntax Warning: Unclosed token "${stack[stack.length - 1]}" at EOF`
    }
  }

  return { valid: true }
}

/**
 * Autonomous Aegis Code Engineer execution loop
 */
export async function executeAegisCodeEngineer(params: CodeEngineerParams): Promise<CodeEngineerResult> {
  const { targetFilePath, action, instructions, codeSnippet } = params
  const safePath = resolveSafePath(targetFilePath)
  const fileExists = existsSync(safePath)

  // 1. INSPECT ACTION
  if (action === 'INSPECT') {
    if (!fileExists) {
      return {
        status: 'ERROR',
        action,
        path: targetFilePath,
        message: `File does not exist: ${targetFilePath}`
      }
    }

    const content = readFileSync(safePath, 'utf-8')
    const lines = content.split('\n')
    const preview = lines.slice(0, 30).join('\n')

    return {
      status: 'SUCCESS',
      action,
      path: targetFilePath,
      lines: lines.length,
      contentPreview: preview,
      message: `Inspected ${targetFilePath}: ${lines.length} lines total.`
    }
  }

  // 2. CREATE ACTION
  if (action === 'CREATE') {
    const code = codeSnippet || `// Auto-generated by Aegis Code Engineer for: ${instructions}\nexport {};\n`
    const syntax = validateCodeSyntax(code, targetFilePath.split('.').pop() || '')
    if (!syntax.valid) {
      throw new Error(`Syntax validation failed: ${syntax.error}`)
    }

    // Persist to local filesystem
    writeFileSync(safePath, code, 'utf-8')

    // Commit to GitHub via toolRegistry
    try {
      await executeGithubManageFile('write', targetFilePath, code, `feat: create ${targetFilePath} via Aegis Code Engineer`)
    } catch {}

    return {
      status: 'SUCCESS',
      action,
      path: targetFilePath,
      lines: code.split('\n').length,
      diffSummary: `Created ${targetFilePath} with ${code.split('\n').length} lines.`,
      message: `Successfully created and committed ${targetFilePath}.`
    }
  }

  // 3. REFACTOR ACTION
  if (action === 'REFACTOR') {
    if (!fileExists) {
      throw new Error(`Cannot refactor non-existent file: ${targetFilePath}`)
    }

    const originalContent = readFileSync(safePath, 'utf-8')
    const updatedCode = codeSnippet || `${originalContent}\n// Refactored by Aegis: ${instructions}\n`

    const syntax = validateCodeSyntax(updatedCode, targetFilePath.split('.').pop() || '')
    if (!syntax.valid) {
      throw new Error(`Refactoring syntax validation failed: ${syntax.error}`)
    }

    writeFileSync(safePath, updatedCode, 'utf-8')

    try {
      await executeGithubManageFile('write', targetFilePath, updatedCode, `refactor: ${targetFilePath} - ${instructions}`)
    } catch {}

    return {
      status: 'SUCCESS',
      action,
      path: targetFilePath,
      lines: updatedCode.split('\n').length,
      diffSummary: `Updated ${targetFilePath} (${originalContent.length} bytes -> ${updatedCode.length} bytes).`,
      message: `Successfully refactored ${targetFilePath} per instructions: "${instructions}".`
    }
  }

  throw new Error(`Unknown action: ${action}. Must be CREATE, REFACTOR, or INSPECT.`)
}

